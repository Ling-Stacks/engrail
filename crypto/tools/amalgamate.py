#!/usr/bin/env python3
"""
amalgamate.py -- produce the single-file Engrail Crypto distribution.

Output (into crypto/dist/):
  engrail_crypto.h   unified public header (SM2/SM3/Ed25519/SHA-512/
                     HMAC/HKDF/PBKDF2/ChaCha20/CSPRNG)
  engrail_crypto.c   all implementations in one translation unit

Drop the two files into any C99 project and compile engrail_crypto.c
with your sources. No configuration, no dependencies, no libc beyond
<string.h>/<stdio.h>/<stdlib.h>.

Part of Engrail -- MIT licensed. Community: https://t.me/Stack_Traces
"""

import os
import re
import sys
from pathlib import Path

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
INC = os.path.join(ROOT, "include", "activation")
SRC = os.path.join(ROOT, "src")

DISTDIR = None  # output directory; set once by main() from a validated argument


def resolve_distdir(distdir):
    """Re-anchor distdir under the crypto/ subtree of the repository.

    Every path component of the argument is parsed into a safe list
    (empty and "." dropped, ".." and drive-letter components rejected),
    and the output directory is rebuilt as crypto/<components> — the raw
    argument is never used as a filesystem path.
    """
    parts = [p for p in distdir.replace("\\", "/").split("/")
             if p not in ("", ".")]
    if ".." in parts or any(":" in p for p in parts):
        sys.exit("amalgamate: refusing distdir outside the crypto subtree: %s"
                 % distdir)
    base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    return os.path.join(base, *parts) if parts else base

HEADERS = [
    "version.h", "sha512.h", "hmac.h", "ed25519.h", "random.h",
    "sm3.h", "chacha20.h", "kdf.h", "sm2.h",
]

SOURCES = [
    "crypto/sha512.c", "crypto/hmac.c", "crypto/ed25519.c",
    "crypto/random.c", "crypto/chacha20.c", "crypto/sm3.c",
    "crypto/sm2.c", "core/kdf.c",
]

# The crypto subset does not include license.h, but sm2.h/sm3.h/kdf.h
# return act_status. Keep the ABI identical to the full library
# (same names, same values, harden.h range included for stability).
STATUS_SECTION = """\
/* ==== status.h (crypto subset; values match the full library) ==== */
typedef enum act_status {
    ACT_OK               =  0,
    ACT_ERR_ARG          = -1,
    ACT_ERR_FORMAT       = -2,
    ACT_ERR_VERSION      = -3,
    ACT_ERR_PRODUCT      = -4,
    ACT_ERR_SIGNATURE    = -5,
    ACT_ERR_MACHINE      = -6,
    ACT_ERR_EXPIRED      = -7,
    ACT_ERR_STATE_MISSING= -8,
    ACT_ERR_STATE_IO     = -9,
    ACT_ERR_STATE_CORRUPT= -10,
    ACT_ERR_REVOKED      = -11,
    ACT_ERR_DEBUGGER     = -12,
    ACT_ERR_INTEGRITY    = -13,
    ACT_ERR_MISMATCH     = -14,
    ACT_ERR_ENTROPY      = -15
} act_status;
"""

BANNER = """\
/*
 * Engrail Crypto {ver} -- single-file modern-crypto amalgamation
 * Generated by crypto/tools/amalgamate.py; DO NOT EDIT BY HAND.
 *
 * Primitives: Ed25519 (RFC 8032) . SM2 (GB/T 32918) . SM3 (GB/T 32905)
 *             SHA-512 (FIPS 180-4) . HMAC (RFC 4231) . HKDF (RFC 5869)
 *             PBKDF2 (RFC 8018) . ChaCha20 (RFC 8439) . OS CSPRNG
 *
 * MIT License -- Copyright (c) 2026 Engrail Contributors
 * Community: https://t.me/Stack_Traces
 *
 * Usage: #include "engrail_crypto.h"  and compile engrail_crypto.c
 */
"""


def strip_local_includes(text):
    return re.sub(r'^#include "activation/[^"]+"\s*$(\n)?', '', text,
                  flags=re.M)


def strip_license_blocks(text):
    return re.sub(r'/\*\n \* MIT License.*?\*/\n', '', text, flags=re.S)


def read_version():
    vh = os.path.join(INC, "version.h")
    m = re.search(r'#define ACT_VERSION\s+"([^"]+)"', open(vh).read())
    return m.group(1) if m else "0.0.0"


def write_distribution():
    """Write engrail_crypto.{h,c} into DISTDIR."""
    os.makedirs(DISTDIR, exist_ok=True)
    version = read_version()

    parts = [BANNER.replace("{ver}", version),
             "#ifndef ENGRAIL_CRYPTO_AMALGAMATED_H\n"
             "#define ENGRAIL_CRYPTO_AMALGAMATED_H\n\n",
             STATUS_SECTION]
    for name in HEADERS:
        body = strip_license_blocks(strip_local_includes(
            open(os.path.join(INC, name), encoding="utf-8").read()))
        body = re.sub(r'#ifndef ACTIVATION_[A-Z0-9_]+_H\n', '', body)
        body = re.sub(r'#define ACTIVATION_[A-Z0-9_]+_H\n', '', body)
        body = re.sub(r'#endif /\* ACTIVATION_[A-Z0-9_/]+_H \*/\s*$',
                      '', body, flags=re.M)
        parts.append("/* ==== %s ==== */\n%s\n" % (name, body))
    parts.append("#endif /* ENGRAIL_CRYPTO_AMALGAMATED_H */\n")
    Path(DISTDIR, "engrail_crypto.h").write_text(
        "\n".join(parts), encoding="utf-8", newline="\n")

    parts = [BANNER.replace("{ver}", version),
             # Feature-macro prelude: the amalgamation must compile under
             # a user's strict -std=c99 too (the per-source preludes land
             # mid-file after concatenation and would be too late).
             '#if !defined(_GNU_SOURCE) && !defined(_DARWIN_C_SOURCE) && '
             '!defined(_DEFAULT_SOURCE)\n'
             '#  if defined(__APPLE__)\n'
             '#    define _DARWIN_C_SOURCE 1\n'
             '#  elif defined(__linux__) || defined(__ANDROID__)\n'
             '#    define _GNU_SOURCE 1\n'
             '#  else\n'
             '#    define _DEFAULT_SOURCE 1\n'
             '#  endif\n'
             '#endif\n\n',
             '#include "engrail_crypto.h"\n']
    for rel in SOURCES:
        body = strip_license_blocks(strip_local_includes(
            open(os.path.join(SRC, rel), encoding="utf-8").read()))
        parts.append("/* ==== src/%s ==== */\n%s\n" % (rel, body))
    Path(DISTDIR, "engrail_crypto.c").write_text(
        "\n".join(parts), encoding="utf-8", newline="\n")

    for name in ("engrail_crypto.h", "engrail_crypto.c"):
        path = os.path.join(DISTDIR, name)
        print("wrote %-44s %7d bytes" % (path, os.path.getsize(path)))
    print("community: https://t.me/Stack_Traces")


def main(argv):
    global DISTDIR
    arg = argv[1] if len(argv) > 1 else "dist"
    DISTDIR = resolve_distdir(arg)
    write_distribution()


if __name__ == "__main__":
    sys.exit(main(sys.argv) or 0)
